"""Evaluate a complete REGENERATED portable cohort, never partial paper workers.

Requires four directories named seed_946201 ... seed_946204, each generated by
train_bct1.py. This route evaluates the two-hybrid primary comparison only;
linked combined-BDT reference reproduction is not implemented in this release.
It is an unvalidated GPU reproduction template, not the historical evaluator.
"""
from __future__ import annotations
import argparse,json,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--cohort-root',type=Path,required=True)
    p.add_argument('--data',type=Path,required=True)
    p.add_argument('--out',type=Path,required=True)
    p.add_argument('--allow-evaluation',action='store_true')
    a=p.parse_args()
    if not a.allow_evaluation:p.error('No evaluations started: --allow-evaluation is required')
    from repro.training import (ARMS,FORMAT,MODS,load,digest_file,check_exact_cache,
                               configure_cpu,helpers,code_identity,report_evaluate,torch)
    from repro.results import SEEDS,paired
    if a.out.exists():raise FileExistsError('New evaluation output directory required')
    if not torch.cuda.is_available() or not torch.cuda.is_bf16_supported():raise RuntimeError('CUDA BF16 required')
    hashes=check_exact_cache(a.data);bindings=[]
    # Inspect and byte-verify ALL eight endpoints before deserialization or any loss computation.
    for seed in SEEDS:
        root=a.cohort_root/f'seed_{seed}'
        r=json.loads((root/'RESULT.json').read_text())
        if r['format']!=FORMAT or r['mode']!='UNVALIDATED_GPU_PORTABLE_REPRODUCTION' or r['seed']!=int(seed):raise RuntimeError('Wrong family/mode')
        if r['continuation_end_phase']!=3000 or r['parent_updates']!=7630 or r['prefix_updates']!=200:raise RuntimeError('Wrong phase/budget')
        if r['cache']!=hashes or r['code_identity']!=code_identity() or set(r['endpoints'])!=set(ARMS):raise RuntimeError('Code/data/arms differ')
        for arm in ARMS:
            path=root/(arm+'_endpoint.pt');expected=r['endpoints'][arm]['checkpoint_sha256']
            if digest_file(path)!=expected or path.with_suffix('.sha256').read_text().strip()!=expected:raise RuntimeError('Endpoint binding mismatch')
            bindings.append((seed,arm,path,expected))
    configure_cpu(4);a.out.mkdir(parents=True)
    (a.out/'EIGHT_ENDPOINTS_VERIFIED.json').write_text(json.dumps([{'seed':s,'arm':b,'sha256':h} for s,b,f,h in bindings],indent=2)+'\n')
    scores={s:{} for s in SEEDS}
    for seed,arm,path,expected in bindings:
        ck=load(path)
        if ck['seed']!=int(seed) or ck['code_identity']!=code_identity() or ck['opt']['phase']!=3000 or ck['opt']['bct']['mode']!=arm:raise RuntimeError('Payload identity mismatch')
        cfg=MODS['native'].ExperimentConfig(**ck['config'])
        model=helpers.build(MODS['native'],cfg,int(seed)).to('cuda:0');model.load_state_dict(ck['model'],strict=True)
        scores[seed][arm]=report_evaluate(model,cfg,a.data/'val.bin')
        del model,ck
    diffs=[scores[s][ARMS[0]]['loss']-scores[s][ARMS[1]]['loss'] for s in SEEDS]
    result={'scope':'REGENERATED portable four-family cohort; not new results for the submitted study; GPU parity unvalidated',
            'scores':scores,'primary_contrast':paired(diffs),'linked_reference_contrasts_available':False}
    (a.out/'REGENERATED_REPORT.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result,indent=2))

if __name__=='__main__':main()
